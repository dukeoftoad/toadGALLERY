package io.github.dukeoftoad.gallery.data.catalogue.room

import android.content.Context
import androidx.room.Database
import androidx.room.Room
import androidx.room.RoomDatabase
import androidx.room.migration.Migration
import androidx.sqlite.db.SupportSQLiteDatabase

/**
 * The Room database of the Phase 4 media catalogue (ADR-0006's persistence
 * layer; audit item "Room catalogue").
 *
 * Migration policy --- deliberate and non-negotiable: NO destructive
 * migration. The catalogue is a CACHE (it can always be rebuilt from a full
 * MediaStore scan), but its tombstones and scan checkpoints are the only
 * record of what the AI engines should forget, so a silent
 * `fallbackToDestructiveMigration` would trade a crash today for invisible
 * index corruption tomorrow. Future schema versions must ship explicit
 * `Migration` objects, and version 1's schema below is the baseline they
 * migrate from.
 *
 * Schema export (Phase 4 audit finding K): `exportSchema = true` with the
 * `room.schemaLocation` KSP argument (apps/gallery/build.gradle.kts) writes
 * one versioned JSON snapshot per database version under
 * apps/gallery/schemas/, committed to source control. The v1, v2 and v3
 * snapshots are generated by their respective builds; any schema-changing
 * release MUST have its new snapshot reviewed against the shipped
 * `Migration` before release --- the snapshots are the reviewable history
 * migrations are judged against.
 *
 * Version history:
 * - v1 -> v2 (r12 round): the capture-date provenance columns
 *   (`resolvedCaptureDateMillis`, `resolvedCaptureDateZoneOffsetMinutes`,
 *   `resolvedCaptureDateSource`) added to `catalogue_items` by
 *   [MIGRATION_1_2] --- three plain nullable columns, no table rebuild, no
 *   data loss. `DEFAULT NULL` in the migration SQL matches the entities'
 *   no-default nullable declarations exactly (SQLite treats
 *   `DEFAULT NULL` as "no default", so Room's schema validation sees the
 *   migrated table identical to the freshly-created one).
 * - v2 -> v3 (r13 round): the display/shape ride-along columns
 *   (`displayName`, `width`, `height`, `durationMs`, `isFavorite`) added to
 *   `catalogue_items` by [MIGRATION_2_3] --- the same `ADD COLUMN`-only,
 *   non-destructive shape. Existing rows read the neutral "unknown"
 *   values (NULL name, 0 dimensions, 0 duration, false favorite) until the
 *   next authoritative scan refreshes them, which is exactly the record
 *   fields' documented default semantics.
 *
 * Untested Android-adjacent code per ADR-0016; behavior is pinned by the
 * pure-type tests around [io.github.dukeoftoad.gallery.data.catalogue
 * .InMemoryMediaCatalogue] and the reconciler.
 */
@Database(
    entities = [
        CatalogueItemEntity::class,
        CatalogueTombstoneEntity::class,
        ScanCheckpointEntity::class,
    ],
    version = 3,
    exportSchema = true,
)
abstract class MediaCatalogueDatabase : RoomDatabase() {

    /** The catalogue's only DAO; see [CatalogueDao] for the surface. */
    abstract fun catalogueDao(): CatalogueDao

    companion object {
        /**
         * App-private database file. Not `allowBackup`-sensitive --- the
         * catalogue is rebuildable device-local state --- but deliberately
         * distinct from any future engine-owned ML database file so the
         * audit's "separate stores" boundary is visible on disk too.
         */
        private const val DATABASE_NAME = "media_catalogue.db"

        /**
         * v1 -> v2 (r12 round): adds the capture-date provenance columns to
         * `catalogue_items`. Three nullable columns, `ADD COLUMN` only ---
         * no table rebuild, so existing rows keep every value and simply
         * read `NULL` ("never resolved") for the new fields, which is
         * exactly the semantics the nullable record fields document.
         *
         * The `DEFAULT NULL` clause is deliberate, not decoration: it makes
         * the migrated schema byte-identical to the CREATE TABLE Room
         * generates for the v2 entities (a nullable column with no
         * declared default --- SQLite stores `DEFAULT NULL` as "no
         * default"), so Room's open-time schema validation passes without
         * `@ColumnInfo(defaultValue = ...)` annotations.
         */
        val MIGRATION_1_2: Migration = object : Migration(1, 2) {
            override fun migrate(db: SupportSQLiteDatabase) {
                db.execSQL(
                    "ALTER TABLE catalogue_items " +
                        "ADD COLUMN resolvedCaptureDateMillis INTEGER DEFAULT NULL",
                )
                db.execSQL(
                    "ALTER TABLE catalogue_items " +
                        "ADD COLUMN resolvedCaptureDateZoneOffsetMinutes INTEGER DEFAULT NULL",
                )
                db.execSQL(
                    "ALTER TABLE catalogue_items " +
                        "ADD COLUMN resolvedCaptureDateSource TEXT DEFAULT NULL",
                )
            }
        }

        /**
         * v2 -> v3 (r13 round): adds the display/shape ride-along columns to
         * `catalogue_items` --- the fields the timeline's cells render from
         * (display name, pixel dimensions, video duration, favorite flag).
         * Five `ADD COLUMN`s only: no table rebuild, no index, no data loss;
         * existing rows keep every value and read the neutral "unknown"
         * defaults for the new fields until the next authoritative scan
         * re-walks their rows.
         *
         * The defaults follow the entities' declarations exactly:
         * `DEFAULT NULL` for the nullable displayName (SQLite stores it as
         * "no default", byte-identical to Room's generated CREATE TABLE),
         * and `NOT NULL DEFAULT 0` for the four primitive columns --- SQLite
         * requires a non-null default on `ADD COLUMN ... NOT NULL`, Room's
         * schema validation ignores the clause because the entities declare
         * no `@ColumnInfo(defaultValue = ...)`, and the value 0/false is
         * precisely the record fields' "unknown" zero-point.
         */
        val MIGRATION_2_3: Migration = object : Migration(2, 3) {
            override fun migrate(db: SupportSQLiteDatabase) {
                db.execSQL(
                    "ALTER TABLE catalogue_items " +
                        "ADD COLUMN displayName TEXT DEFAULT NULL",
                )
                db.execSQL(
                    "ALTER TABLE catalogue_items " +
                        "ADD COLUMN width INTEGER NOT NULL DEFAULT 0",
                )
                db.execSQL(
                    "ALTER TABLE catalogue_items " +
                        "ADD COLUMN height INTEGER NOT NULL DEFAULT 0",
                )
                db.execSQL(
                    "ALTER TABLE catalogue_items " +
                        "ADD COLUMN durationMs INTEGER NOT NULL DEFAULT 0",
                )
                db.execSQL(
                    "ALTER TABLE catalogue_items " +
                        "ADD COLUMN isFavorite INTEGER NOT NULL DEFAULT 0",
                )
            }
        }

        /**
         * Builds the singleton-scope database for the app. Callers own the
         * instance lifetime (one per process, via whatever dependency
         * holder the app settles on); [context.applicationContext] is used
         * so no Activity can leak through the builder. Explicit
         * migrations only ([MIGRATION_1_2], [MIGRATION_2_3]) --- NO
         * `fallbackToDestructiveMigration`, ever; see the class KDoc.
         */
        fun build(context: Context): MediaCatalogueDatabase =
            Room.databaseBuilder(
                context.applicationContext,
                MediaCatalogueDatabase::class.java,
                DATABASE_NAME,
                // No fallbackToDestructiveMigration here, ever --- see the
                // class KDoc. An incompatible future schema must fail loud
                // (IllegalStateException on open), not wipe silently.
            )
                .addMigrations(MIGRATION_1_2, MIGRATION_2_3)
                .build()
    }
}
